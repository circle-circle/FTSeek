def build_strategy_analysis_prompt(
    title: str,
    content: str,
    source: str = "unknown",
    pub_time: str = "",
    event_name: str = "",
    event_sector: str = "",
    static_logic: str = "",
    watchlist_str: str = "",
    market_data_str: str = "",
    geo_scan: dict = None,
) -> str:
    """构建完整的 LLM 新闻分析 prompt，整合地缘政治预筛标记"""
    geo_section = build_geo_analysis_section(geo_scan)
    
    prompt = STRATEGY_ANALYSIS_PROMPT.format(
        geo_analysis_section=geo_section,
        title=title,
        content=content,
        source=source,
        pub_time=pub_time,
        event_name=event_name,
        event_sector=event_sector,
        static_logic=static_logic,
        watchlist_str=watchlist_str or "\u65e0",
        market_data_str=market_data_str or "\u65e0\u5b9e\u65f6\u6570\u636e",
    )
    return prompt
